<?php

namespace LaravelEgypt\DataLens\Livewire;

use Livewire\Component;
use Livewire\WithPagination;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;

class TableViewer extends Component
{
    use WithPagination;

    public $connection;
    public $table;
    
    public $sortColumn = null;
    public $sortDirection = 'asc';
    
    public $showAddModal = false;
    public $newRowData = [];
    
    public $showEditModal = false;
    public $editingRowId = null;
    public $editingRowKey = null;
    public $editRowData = [];
    
    public $search = '';

    public function updatingSearch()
    {
        $this->resetPage();
    }

    public function mount($connection, $table)
    {
        $this->connection = $connection;
        $this->table = $table;
    }
    
    public function sortBy($columnName)
    {
        if ($this->sortColumn === $columnName) {
            $this->sortDirection = $this->sortDirection === 'asc' ? 'desc' : 'asc';
        } else {
            $this->sortColumn = $columnName;
            $this->sortDirection = 'asc';
        }
        $this->resetPage();
    }

    public function deleteRow($primaryKeyColumn, $id)
    {
        if (!$primaryKeyColumn || !$id) return;
        
        try {
            DB::connection($this->connection)
                ->table($this->table)
                ->where($primaryKeyColumn, $id)
                ->delete();
        } catch (\Exception $e) {
            Log::error('DataLens delete error: ' . $e->getMessage());
            $this->addError('delete', 'Could not delete row: ' . $e->getMessage());
        }
    }

    public function openAddModal()
    {
        $this->newRowData = [];
        $this->resetErrorBag('insert');
        $this->showAddModal = true;
    }

    public function closeAddModal()
    {
        $this->showAddModal = false;
        $this->newRowData = [];
    }

    public function saveRow()
    {
        $dataToInsert = [];
        foreach ($this->newRowData as $col => $val) {
            if ($val !== '' && $val !== null) {
                $dataToInsert[$col] = $val;
            }
        }
        
        try {
            DB::connection($this->connection)
                ->table($this->table)
                ->insert($dataToInsert);
                
            $this->showAddModal = false;
            $this->newRowData = [];
            $this->resetPage();
        } catch (\Exception $e) {
            Log::error('DataLens insert error: ' . $e->getMessage());
            $this->addError('insert', 'Could not add row: ' . $e->getMessage());
        }
    }
    
    public function openEditModal($primaryKeyColumn, $id)
    {
        $this->resetErrorBag('update');
        $this->editingRowKey = $primaryKeyColumn;
        $this->editingRowId = $id;
        
        $row = DB::connection($this->connection)
            ->table($this->table)
            ->where($primaryKeyColumn, $id)
            ->first();
            
        if ($row) {
            $this->editRowData = (array) $row;
            $this->showEditModal = true;
        } else {
            $this->addError('delete', 'Row not found for editing.');
        }
    }

    public function closeEditModal()
    {
        $this->showEditModal = false;
        $this->editingRowId = null;
        $this->editingRowKey = null;
        $this->editRowData = [];
    }
    
    public function updateRow()
    {
        if (!$this->editingRowKey || !$this->editingRowId) return;
        
        try {
            $dataToUpdate = $this->editRowData;
            
            DB::connection($this->connection)
                ->table($this->table)
                ->where($this->editingRowKey, $this->editingRowId)
                ->update($dataToUpdate);
                
            $this->closeEditModal();
        } catch (\Exception $e) {
            Log::error('DataLens update error: ' . $e->getMessage());
            $this->addError('update', 'Could not update row: ' . $e->getMessage());
        }
    }

    public function render()
    {
        $columnNames = [];
        $primaryKey = null;
        $autoGeneratedColumns = [];

        try {
            $columns = Schema::connection($this->connection)->getColumns($this->table);
            $indexes = Schema::connection($this->connection)->getIndexes($this->table);

            foreach ($indexes as $index) {
                if ($index['primary']) {
                    $primaryKey = $index['columns'][0] ?? null;
                    break;
                }
            }

            $textColumns = [];
            $numericColumns = [];

            foreach ($columns as $column) {
                $columnNames[] = $column['name'];
                
                $isAutoIncrement = !empty($column['auto_increment']);
                $isGenerated = !empty($column['generation']);
                
                if ($isAutoIncrement || $isGenerated) {
                    $autoGeneratedColumns[] = $column['name'];
                }
                
                $type = strtolower($column['type_name'] ?? '');
                if (preg_match('/char|text|string|uuid/i', $type)) {
                    $textColumns[] = $column['name'];
                } elseif (preg_match('/int|decimal|numeric|float|double/i', $type)) {
                    $numericColumns[] = $column['name'];
                }
            }
            
            if (empty($textColumns) && empty($numericColumns)) {
                $textColumns = $columnNames;
            }
        } catch (\Exception $e) {
            Log::error('DataLens schema error: ' . $e->getMessage());
            $textColumns = $columnNames;
        }

        $query = DB::connection($this->connection)->table($this->table);
        
        if (!empty($this->search)) {
            $query->where(function($q) use ($textColumns, $numericColumns) {
                foreach ($textColumns as $col) {
                    $q->orWhere($col, 'like', '%' . $this->search . '%');
                }
                if (is_numeric($this->search)) {
                    foreach ($numericColumns as $col) {
                        $q->orWhere($col, $this->search);
                    }
                }
            });
        }
        
        if ($this->sortColumn) {
            $query->orderBy($this->sortColumn, $this->sortDirection);
        }
        
        $rows = $query->paginate(20);

        return view('datalens::livewire.table-viewer', [
            'rows' => $rows,
            'columnNames' => $columnNames,
            'primaryKey' => $primaryKey,
            'autoGeneratedColumns' => $autoGeneratedColumns,
        ]);
    }
}
